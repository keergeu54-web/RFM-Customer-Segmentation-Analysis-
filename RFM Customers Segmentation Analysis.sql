-- 5 Top Revenue Drivers vs. Churn Risks 
-- Which specific customer IDs represent the highest monetary value but have not purchased recently 
-- (e.g., At Risk / Champions who are drifting away)?
WITH HighValueCustomers AS (
    SELECT 
        CustomerID,
        SUM(Quantity * UnitPrice) AS TotalSpend
    FROM data
    WHERE CustomerID IS NOT NULL
    GROUP BY CustomerID
    HAVING SUM(Quantity * UnitPrice) > 5000
)
SELECT 
    c.CustomerID,
    c.TotalSpend
FROM HighValueCustomers c
ORDER BY c.TotalSpend DESC;	

