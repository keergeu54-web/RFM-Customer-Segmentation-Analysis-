-- RFM Customer Segmentation Analysis


-- 1 Segment_Distribution
-- What is the total count and percentage share of customers in each segment?
WITH Customer_Spend AS (
    SELECT 
        CustomerID,
        SUM(Quantity * UnitPrice) AS Total_Spend
    FROM data
    WHERE CustomerID IS NOT NULL AND Quantity > 0 AND UnitPrice > 0
    GROUP BY CustomerID
),
Segmented_Customers AS (
    SELECT 
        CustomerID,
        CASE 
            WHEN Total_Spend > 5000 THEN 'high value'
            WHEN Total_Spend BETWEEN 1000 AND 5000 THEN 'Medium Value'
            ELSE 'Low Value'
        END AS Segment
    FROM Customer_Spend
)
SELECT 
    Segment,
    COUNT(CustomerID) AS Total_Customers,
    ROUND(100.0 * COUNT(CustomerID) / SUM(COUNT(CustomerID)) OVER(), 2) AS Percentage_Share
FROM Segmented_Customers
GROUP BY Segment
ORDER BY Total_Customers DESC;


-- Helps the retailer identify its largest customer groups, allocate marketing 
-- resources, and decide which segments need retention or re-engagement campaigns.
