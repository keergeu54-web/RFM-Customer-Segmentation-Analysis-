-- 2 Revenue_Share 
-- What is the total revenue contribution and percentage of total revenue generated by each segment

SELECT
    Country AS segment,
    ROUND(SUM(Quantity * UnitPrice), 2) AS total_revenue,
    ROUND(100.0 * SUM(Quantity * UnitPrice)
          / SUM(SUM(Quantity * UnitPrice)) OVER (), 2) percentage
FROM data
WHERE Quantity > 0
  AND UnitPrice > 0
GROUP BY Country
ORDER BY total_revenue DESC
limit 5;

